static void UART_Printf(const char *format, ...)
{
  char buffer[128];
  va_list arguments;

  va_start(arguments, format);

  int length = vsnprintf(buffer, sizeof(buffer), format, arguments);

  va_end(arguments);

  if (length < 0)
  {
    return;
  }

  if (length >= (int)sizeof(buffer))
  {
    length = sizeof(buffer) - 1;
  }

  HAL_UART_Transmit(&huart2,
                    (uint8_t *)buffer,
                    (uint16_t)length,
                    HAL_MAX_DELAY);
}
