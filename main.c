/**
  * @brief  Function implementing the Aquisition thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartAquisition */
void StartAquisition(void *argument)
{
  /* USER CODE BEGIN 5 */
  uint32_t measurement = 0;

  for (;;)
  {
    measurement++;

    osStatus_t status = osMessageQueuePut(
        MeasurementQueueHandle,
        &measurement,
        0,
        0);

    if (status != osOK)
    {
      UART_Printf("Queue pleine, mesure %lu perdue\r\n",
                  (unsigned long)measurement);
    }

    osDelay(500);
  }
  /* USER CODE END 5 */
}

/* USER CODE BEGIN Header_StartTraitement */
/**
* @brief Function implementing the Traitement thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartTraitement */
void StartTraitement(void *argument)
{
  /* USER CODE BEGIN StartTraitement */
  uint32_t measurement;
  uint32_t processedValue;

  for (;;)
  {
    osStatus_t status = osMessageQueueGet(
        MeasurementQueueHandle,
        &measurement,
        NULL,
        osWaitForever);

    if (status == osOK)
    {
      processedValue = measurement * 2U;

      UART_Printf("Mesure recue : %lu | Valeur traitee : %lu\r\n",
                  (unsigned long)measurement,
                  (unsigned long)processedValue);
    }
  }
  /* USER CODE END StartTraitement */
}

